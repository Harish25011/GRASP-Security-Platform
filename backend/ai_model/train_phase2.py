"""
Phase 2 Model Training - trains all Phase 2 AI models:
  1. Autoencoder for Zero-Day detection
  2. LSTM for Temporal/APT detection
  3. IsolationForest for persistent Behavior agent

Requires: vectors.npz (generated by initial_train.py)
"""
import os
import sys
import numpy as np
import torch
import torch.nn as nn
import joblib

# Ensure project root is on path
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.dirname(__file__))))

CHECKPOINT_DIR = os.path.join("backend", "checkpoints")
DATA_DIR = os.path.join("backend", "data")
VECTORS_PATH = os.path.join(DATA_DIR, "vectors.npz")


def train_autoencoder():
    """Train Anomaly Autoencoder on BENIGN-only traffic vectors."""
    from backend.models.autoencoder import AnomalyAutoencoder

    print("\n" + "=" * 60)
    print("  TRAINING: Anomaly Autoencoder (Zero-Day Detection)")
    print("=" * 60)

    if not os.path.exists(VECTORS_PATH):
        print("[ERROR] vectors.npz not found. Run initial_train.py first.")
        return False

    data = np.load(VECTORS_PATH)
    X, y = data["X"], data["y"]
    X_benign = X[y == 0]
    print(f"  Benign samples: {len(X_benign)}")
    print(f"  Feature dims:   {X_benign.shape[1]}")

    if len(X_benign) < 10:
        print("[WARN] Not enough benign vectors. Using all data.")
        X_benign = X

    X_tensor = torch.tensor(X_benign, dtype=torch.float32)
    input_dim = X_tensor.shape[1]

    model = AnomalyAutoencoder(input_dim=input_dim)
    optimizer = torch.optim.Adam(model.parameters(), lr=0.001)
    criterion = nn.MSELoss()

    model.train()
    best_loss = float("inf")
    for epoch in range(100):
        optimizer.zero_grad()
        output = model(X_tensor)
        loss = criterion(output, X_tensor)
        loss.backward()
        optimizer.step()

        if loss.item() < best_loss:
            best_loss = loss.item()

        if (epoch + 1) % 20 == 0:
            print(f"  Epoch {epoch+1:3d}/100 - Loss: {loss.item():.6f}")

    save_path = os.path.join(CHECKPOINT_DIR, "autoencoder.pt")
    torch.save(model.state_dict(), save_path)
    print(f"  [OK] Autoencoder saved to {save_path} (best loss: {best_loss:.6f})")

    # Also save benign vectors for reference
    benign_path = os.path.join(DATA_DIR, "benign_vectors.npy")
    np.save(benign_path, X_benign)
    print(f"  [OK] Benign vectors saved to {benign_path}")

    return True


def train_lstm():
    """Train Attack LSTM on sequential windows of agent score vectors."""
    from backend.models.attack_lstm import AttackLSTM

    print("\n" + "=" * 60)
    print("  TRAINING: Attack LSTM (Temporal/APT Detection)")
    print("=" * 60)

    if not os.path.exists(VECTORS_PATH):
        print("[ERROR] vectors.npz not found. Run initial_train.py first.")
        return False

    data = np.load(VECTORS_PATH)
    X, y = data["X"], data["y"]
    print(f"  Total samples: {len(X)}")

    # Create sliding windows
    window_size = 50
    if len(X) < window_size + 10:
        window_size = max(5, len(X) // 3)
        print(f"  [WARN] Small dataset. Using window_size={window_size}")

    X_seq, y_seq = [], []
    for i in range(len(X) - window_size):
        X_seq.append(X[i : i + window_size])
        y_seq.append(y[i + window_size - 1])

    X_seq = np.array(X_seq, dtype=np.float32)
    y_seq = np.array(y_seq, dtype=np.float32)
    print(f"  Sequences: {len(X_seq)} of shape ({window_size}, {X.shape[1]})")

    # Save for future retraining
    seq_path = os.path.join(DATA_DIR, "sequence_vectors.npz")
    np.savez(seq_path, X=X_seq, y=y_seq)

    X_tensor = torch.tensor(X_seq, dtype=torch.float32)
    y_tensor = torch.tensor(y_seq, dtype=torch.float32)

    input_dim = X_seq.shape[2]
    model = AttackLSTM(input_dim=input_dim, hidden_dim=64, num_layers=2)
    optimizer = torch.optim.Adam(model.parameters(), lr=0.001)
    criterion = nn.BCELoss()

    model.train()
    for epoch in range(30):
        optimizer.zero_grad()
        output = model(X_tensor).squeeze()
        loss = criterion(output, y_tensor)
        loss.backward()
        optimizer.step()

        if (epoch + 1) % 5 == 0:
            preds = (output > 0.5).float()
            acc = (preds == y_tensor).float().mean()
            print(f"  Epoch {epoch+1:3d}/30 - Loss: {loss.item():.4f}, Acc: {acc.item():.4f}")

    save_path = os.path.join(CHECKPOINT_DIR, "lstm_apt.pt")
    torch.save(model.state_dict(), save_path)
    print(f"  [OK] LSTM saved to {save_path}")
    return True


def train_behavior_iforest():
    """Train persistent IsolationForest for Behavior Agent."""
    from sklearn.ensemble import IsolationForest

    print("\n" + "=" * 60)
    print("  TRAINING: IsolationForest (Persistent Behavior Agent)")
    print("=" * 60)

    if not os.path.exists(VECTORS_PATH):
        print("[ERROR] vectors.npz not found. Run initial_train.py first.")
        return False

    data = np.load(VECTORS_PATH)
    X = data["X"]

    # Use first 5 features as behavior features (graph-structural)
    X_behavior = X[:, :5] if X.shape[1] >= 5 else X
    print(f"  Training samples: {len(X_behavior)}")
    print(f"  Feature dims:     {X_behavior.shape[1]}")

    clf = IsolationForest(
        contamination=0.1,
        n_estimators=100,
        max_samples="auto",
        random_state=42,
        n_jobs=-1,
    )
    clf.fit(X_behavior)

    save_path = os.path.join(CHECKPOINT_DIR, "behavior_iforest.pkl")
    joblib.dump(clf, save_path)
    print(f"  [OK] IsolationForest saved to {save_path}")

    # Quick test
    scores = clf.decision_function(X_behavior[:10])
    print(f"  Sample decision scores: {[f'{s:.3f}' for s in scores]}")

    return True


def main():
    print("=" * 60)
    print("  GRASP - Phase 2 Model Training Pipeline")
    print("=" * 60)

    os.makedirs(CHECKPOINT_DIR, exist_ok=True)

    results = {}
    results["autoencoder"] = train_autoencoder()
    results["lstm"] = train_lstm()
    results["behavior_iforest"] = train_behavior_iforest()

    print("\n" + "=" * 60)
    print("  TRAINING SUMMARY")
    print("=" * 60)
    for model, success in results.items():
        status = "[OK] SUCCESS" if success else "[FAIL] FAILED"
        print(f"  {model:25s} {status}")
    print("=" * 60)

    # Verify all checkpoints exist
    expected = [
        "grasp_classifier.pt",
        "gcn_model.pt",
        "autoencoder.pt",
        "lstm_apt.pt",
        "behavior_iforest.pkl",
    ]
    print("\n  Checkpoint verification:")
    for ckpt in expected:
        path = os.path.join(CHECKPOINT_DIR, ckpt)
        exists = os.path.exists(path)
        size = os.path.getsize(path) if exists else 0
        status = f"[OK] {size:,} bytes" if exists else "[FAIL] MISSING"
        print(f"    {ckpt:30s} {status}")


if __name__ == "__main__":
    main()
